export function getTimeGreeting(date: Date) {
  const hour = Number(
    new Intl.DateTimeFormat('en-US', {
      timeZone: 'Asia/Shanghai',
      hour: '2-digit',
      hourCycle: 'h23',
    }).format(date),
  );

  if (hour < 5) return '夜猫子还没睡？';
  if (hour < 9) return '早上好，今天也从一次编译开始';
  if (hour < 12) return '上午好，思路正在加载';
  if (hour < 14) return '中午好，先让大脑缓冲一下';
  if (hour < 18) return '下午好，继续保持好奇';
  if (hour < 23) return '晚上好，屏幕还亮着';

  return '夜深了，最后再运行一次';
}
